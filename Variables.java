public class Variables{
    public static void main(String[] args){
        byte myByte=100;
        short myShort=5000;
        int myNum=5;
        float myFloat=5.60f;
        double myDouble=19.99;
        char myChar='A';
        boolean myBoolean=true;
        String myText="Hello World";
        System.out.println("Byte value: " + myByte);
        System.out.println("short values"+ myShort);
        System.out.println("int values" + myNum);
        System.out.println("float values" + myFloat);
        System.out.println("double values" + myDouble);
        System.out.println("char values" + myChar);
        System.out.println("boolean values" + myBoolean);
        System.out.println("String values" + myText);
    }
        
}